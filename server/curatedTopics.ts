export function getCuratedTopic(topicNameOrId: string, size: ListSize): RankedItem[] | null {
  const match = CURATED_TOPICS.find(
    t => t.id === topicNameOrId || t.name.toLowerCase() === topicNameOrId.toLowerCase()
  );
  if (!match) return null;

  return match.items.slice(0, size).map(item => ({
    rank: item.rank,
    title: item.title,
    aliases: item.aliases,
  }));
}
